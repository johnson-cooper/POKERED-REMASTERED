MoveId tmhm_move(u8 number) {
    if (number == 0 || number > NUM_TM_HM) return MOVE_NONE;
    return g_tmhm_moves[number - 1];
}

bool8 pokemon_can_learn_tmhm(PokemonId species, u8 number) {
    if (species == MON_NONE || species > NUM_POKEMON || number == 0 || number > NUM_TM_HM) return FALSE;
    u8 index = (u8)(number - 1);
    return (g_pokemon_tmhm_compat[species][index >> 3] & (1 << (index & 7))) != 0;
}
